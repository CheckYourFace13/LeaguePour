// final/*.mp4|webp|json -> public/media/demo + src/lib/demo-videos.data.ts
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
const S = process.env.SCRATCH;
const R = process.env.REPO_ROOT ?? process.cwd();
const out = path.join(R, "public/media/demo");
fs.mkdirSync(out, { recursive: true });
const ids = ["lp-main", "lp-intro", "vs-main", "vs-intro"];
const data = {};
for (const id of ids) {
  const j = JSON.parse(fs.readFileSync(path.join(S, "final", `${id}.json`), "utf8"));
  const mp4 = fs.readFileSync(path.join(S, "final", `${id}.mp4`));
  fs.copyFileSync(path.join(S, "final", `${id}.mp4`), path.join(out, `${id}.mp4`));
  fs.copyFileSync(path.join(S, "final", `${id}-poster.webp`), path.join(out, `${id}-poster.webp`));
  // Hash the poster too: the same ?v= busts caches for both files (src/lib/demo-videos.ts).
  const poster = fs.readFileSync(path.join(S, "final", `${id}-poster.webp`));
  const version = crypto.createHash("sha1").update(mp4).update(poster).digest("hex").slice(0, 8);
  data[id] = { version, width: j.width, height: j.height, duration: j.duration, cues: j.cues, transcript: j.transcript };
  console.log(id, (mp4.length / 1e6).toFixed(2) + "MB", j.duration + "s", version);
}
const ts = `// GENERATED by the demo recording pipeline from the same timings used to mix the voiceover.
// Do not hand-edit cues; re-run the pipeline. See src/lib/demo-videos.ts.
import type { DemoCue } from "./demo-videos";

type Data = { version: string; width: number; height: number; duration: number; cues: DemoCue[]; transcript: string[] };

export const DEMO_VIDEO_DATA: Record<"lp-main" | "lp-intro" | "vs-main" | "vs-intro", Data> = ${JSON.stringify(data, null, 2)};
`;
fs.writeFileSync(path.join(R, "src/lib/demo-videos.data.ts"), ts);
